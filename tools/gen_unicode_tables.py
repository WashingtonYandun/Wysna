#!/usr/bin/env python3
"""Generate runtime/wysna_unicode_tables.h (canonical decomposition, composition, combining class).

The tables back std/text normalize_nfc / normalize_nfd in the native runtime. They are generated from
Python's unicodedata so the native engines and the reference interpreter agree for the same Unicode version.
Run:  python3 tools/gen_unicode_tables.py [--check]
"""
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / 'runtime' / 'wysna_unicode_tables.h'
HANGUL_S, HANGUL_E = 0xAC00, 0xD7A3


def build():
    decompositions, compositions, classes = [], [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or HANGUL_S <= cp <= HANGUL_E:
            continue
        char = chr(cp)
        raw = unicodedata.decomposition(char)
        if raw and not raw.startswith('<'):
            parts = [int(item, 16) for item in raw.split()]
            assert len(parts) in (1, 2), (hex(cp), raw)
            decompositions.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
            if len(parts) == 2 and unicodedata.normalize('NFC', char) == char:
                compositions.append((parts[0], parts[1], cp))
        ccc = unicodedata.combining(char)
        if ccc:
            classes.append((cp, ccc))
    compositions.sort()
    runs = []
    for cp, ccc in classes:
        if runs and runs[-1][1] + 1 == cp and runs[-1][2] == ccc:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, ccc])
    return decompositions, compositions, runs


def render():
    decompositions, compositions, runs = build()
    lines = [
        '/* Generated by tools/gen_unicode_tables.py; do not edit. */',
        '#ifndef WYSNA_UNICODE_TABLES_H',
        '#define WYSNA_UNICODE_TABLES_H',
        '#include <stdint.h>',
        f'#define WYSNA_UNICODE_VERSION "{unicodedata.unidata_version}"',
        'typedef struct { uint32_t code, first, second; } WysnaUnicodeMapping;',
        'typedef struct { uint32_t first, last; uint8_t ccc; } WysnaUnicodeClassRun;',
        f'#define WYSNA_UNICODE_DECOMPOSITIONS {len(decompositions)}',
        f'#define WYSNA_UNICODE_COMPOSITIONS {len(compositions)}',
        f'#define WYSNA_UNICODE_CLASS_RUNS {len(runs)}',
        'static const WysnaUnicodeMapping wysna_unicode_decompositions[] = {',
    ]
    lines += ['    {0x%X,0x%X,0x%X},' % item for item in decompositions]
    lines += ['};', 'static const WysnaUnicodeMapping wysna_unicode_compositions[] = {']
    lines += ['    {0x%X,0x%X,0x%X},' % item for item in compositions]
    lines += ['};', 'static const WysnaUnicodeClassRun wysna_unicode_classes[] = {']
    lines += ['    {0x%X,0x%X,%d},' % tuple(item) for item in runs]
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv:
        current = OUTPUT.read_text() if OUTPUT.exists() else ''
        if current != text:
            print(f'{OUTPUT} is stale for Unicode {unicodedata.unidata_version}; run tools/gen_unicode_tables.py')
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT} (Unicode {unicodedata.unidata_version})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
