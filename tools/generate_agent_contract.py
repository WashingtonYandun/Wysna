#!/usr/bin/env python3
"""Generate native constants and the package version from one agent contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render_outputs():
    contract = json.loads((ROOT / 'src/common/agent_contract.json').read_text(encoding='utf-8'))
    version = contract['compiler_version']
    topics = sorted(contract['skills'])
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    compact = lambda value: json.dumps(value, ensure_ascii=False, separators=(',', ':'))
    lines = ['# Generated by tools/generate_agent_contract.py; edit src/common/agent_contract.json.\n',
             'fn tool_compiler_version() -> str { return ' + quote(version) + ' }\n',
             'fn tool_language_version() -> str { return ' + quote(contract['language_version']) + ' }\n',
             'fn tool_skills_available_topics() -> str { return ' + quote(', '.join(topics)) + ' }\n',
             'fn tool_skills_topic_content(topic: str) -> str {\n']
    for topic in topics:
        content = contract['skills'][topic].replace('{version}', version)
        lines.append('    if topic == ' + quote(topic) + ' { return ' + quote(content) + ' }\n')
    lines.extend(['    return ""\n}\n', 'fn tool_skills_payload_json(topic: str) -> str {\n'])
    prefix = compact({'schema_version': 'wysna.skills/1', 'compiler_version': version,
                      'available_topics': topics})[:-1] + ',"topic":'
    lines.extend(['    return ' + quote(prefix) + ' + diag_json_quote(topic) + ",\\\"content\\\":" + diag_json_quote(tool_skills_topic_content(topic)) + "}"\n',
                  '}\n', 'fn tool_capabilities_payload_json() -> str {\n'])
    payload = dict(contract['capabilities']['compiler'], compiler_version=version)
    lines.extend(['    return ' + quote(compact(payload)) + '\n', '}\n'])
    return {ROOT / 'selfhost/src/01_agent_contract.wysna': ''.join(lines),
            ROOT / 'src/common/Version.py': '# Generated by tools/generate_agent_contract.py.\nWYSNA_VERSION = ' + quote(version) + '\n'}


def generate(check=False):
    stale = []
    for path, content in render_outputs().items():
        if not path.is_file() or path.read_text(encoding='utf-8') != content:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(content, encoding='utf-8')
    if check and stale:
        raise ValueError('Stale agent contract outputs: ' + ', '.join(stale))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
